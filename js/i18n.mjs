const STORAGE_KEY = "colony-counter-language";
let currentLocale = "ja";

export function resolveLocale(locale) {
  return locale === "en" ? "en" : "ja";
}

export function translate(key, locale = currentLocale, values = {}) {
  const selected = resolveLocale(locale);
  const message = translations[selected][key] ?? translations.ja[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

export function getLocale() {
  return currentLocale;
}

export function applyTranslations(root = document) {
  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(element.dataset.i18n, currentLocale);
  }
  for (const element of root.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel, currentLocale));
  }
  for (const element of root.querySelectorAll("[data-i18n-title]")) {
    element.setAttribute("title", translate(element.dataset.i18nTitle, currentLocale));
  }
  root.documentElement.lang = currentLocale;
}

export function setLocale(locale, { persist = true, root = document } = {}) {
  currentLocale = resolveLocale(locale);
  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEY, currentLocale);
    } catch {}
  }
  const selector = root.getElementById("language");
  if (selector) selector.value = currentLocale;
  applyTranslations(root);
  root.dispatchEvent(new Event("localechange"));
}

export function initI18n(root = document) {
  let savedLocale = "ja";
  try {
    savedLocale = localStorage.getItem(STORAGE_KEY) || "ja";
  } catch {}
  setLocale(savedLocale, { persist: false, root });
  root.getElementById("language")?.addEventListener("change", (event) => {
    setLocale(event.target.value, { root });
  });
}